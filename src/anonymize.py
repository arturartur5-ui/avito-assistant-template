_NUMERAL_MARK = "\u2063"   # ставится после числительного, переведённого в цифры
_CYR_TO_LAT = str.maketrans({"а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x", "і": "i",
                             "А": "A", "Е": "E", "О": "O", "Р": "P", "С": "C", "У": "Y", "Х": "X", "І": "I"})
_NUMERAL_RX = re.compile(r"\b(" + "|".join(sorted(_NUMERALS, key=len, reverse=True)) + r")\b", re.I)
# Кандидат в номер: цифры и похожие на них буквы вперемешку с разделителями.
# Одиночные пробелы внутри допускаются — номер часто пишут группами.
_LOOKALIKE_CHARS = r"\dOoОоQDIlіiІЗзEЧASsбGTBвgq|!"
_LOOKALIKE_SET = set("OoОоQDIlіiІЗзEЧASsбGTBвgq|!")
_MOSTLY_DIGITS = re.compile(rf"(?<![^\W\d_])\d[{_LOOKALIKE_CHARS}*,:;.\-/()\[\]_ #+'~·•]{{5,}}"
                            rf"[{_LOOKALIKE_CHARS}](?![^\W\d_])")


def _fix_digit_lookalikes(text: str) -> str:
    """Буквы вместо цифр — только внутри того, что и так почти целиком цифры.

    «8 9OO 123 45 67» станет номером, а «взнос 600 000» и «мой OZON» не
    пострадают: группа должна начинаться и заканчиваться цифрой, не касаться
    букв по краям и состоять из цифр минимум на три четверти.
    """
    def fix(m: re.Match[str]) -> str:
        tok = m.group(0)
        # одиночная буква на краю группы — это слово рядом, а не часть номера:
        # учитываем это при подсчёте, но сам текст не режем
        counted = re.sub(r"\s+[а-яёa-z]$", "", tok)
        body = re.sub(r"[^\w]", "", counted)
        digits = sum(c.isdigit() for c in body)
        looks = sum(c in _LOOKALIKE_SET for c in body)
        # три подмены в номере — всё ещё номер: цифры и подмены вместе ≥ 90 %
        if len(body) >= 9 and digits >= 4 and digits + looks >= len(body) * 0.9:
            tail = tok[len(counted):]                  # хвост (« в») остаётся как есть
            return counted.translate(_DIGIT_LOOKALIKE) + tail
        return tok

    return _MOSTLY_DIGITS.sub(fix, text)


def _normalize(text: str) -> str:
    """Мягкая: для маскировки. Текст остаётся читаемым — он уйдёт модели.

    Убирает только невидимые знаки и чинит буквы-подмены внутри цифровых
    групп. NFKC здесь нельзя: он превращает «№» в «No», а полноширинные
    знаки — в обычные, и текст клиента меняется без нужды.
    """
    if not text:
        return ""
    return _fix_digit_lookalikes(text.translate(_INVISIBLE))


def _normalize_hard(text: str) -> str:
    """Жёсткая: только для проверки на выходе.

    Результат никому не показывается, поэтому можно искажать как угодно:
    NFKC разворачивает полноширинные цифры и верхние индексы, после чего
    подмены букв ищутся ещё раз.
    """
    if not text:
        return ""
    out = unicodedata.normalize("NFKC", text.translate(_INVISIBLE))
    # диакритика долой только в латинских словах: İvan → Ivan, Jürgen → Jurgen.
    # Кириллицу не трогаем: в NFKD «й» и «ё» распадаются на букву и знак.
    def _plain(m: re.Match[str]) -> str:
        return "".join(c for c in unicodedata.normalize("NFKD", m.group(0)) if unicodedata.category(c) != "Mn")
    out = re.sub(r"\b[A-Za-z\u00C0-\u024F][\w'’\u00C0-\u024F-]*", _plain, out)
    # кириллические двойники внутри латинского слова: Ivаn → Ivan
    out = re.sub(r"\b[A-Za-z][\w'’-]*", lambda m: m.group(0).translate(_CYR_TO_LAT), out)
    # точка словами или в скобках между буквенными группами: «t . me», «t[.]me», «mail точка ru»
    out = re.sub(r"(?<=[a-zа-я0-9])\s*[\[(]?\s*(?:\.|dot|точка|тчк)\s*[\])]?\s*(?=[a-zа-я0-9])", ".", out)
    out = re.sub(r"(\.(?:me|ru|com|рф|net|org))\s*/\s*", r"\1/", out)
    return _fix_digit_lookalikes(out)


def _numerals_to_digits(text: str, mark: bool = False) -> str:
    """«восемь девятьсот двенадцать» → «8 900 12»: для поиска номера словами.

    С mark=True после каждой замены ставится невидимая метка: по ней проверка
    на выходе отличает номер, собранный из слов, от цифр, которые и так были
    в тексте (дата рядом со словами «один раз» — не номер).
    """
    tail = _NUMERAL_MARK if mark else ""
    return _NUMERAL_RX.sub(lambda m: _NUMERALS[m.group(1).lower()] + tail, text)


def _phone_run(m: re.Match[str]) -> str:
    """Подчищающее правило для телефонов в непредусмотренном написании.

    Любая цепочка из 10–11 цифр с какими угодно разделителями, если после
    склейки она выглядит как российский мобильный (9xx…). Диапазоны сумм
    «50 000 - 100 000» не трогаем: у них дефис с пробелами по бокам.
    """
    run = m.group(0)
    if _DASH_SPACED.search(run):
        return run
    digits = re.sub(r"\D", "", run)
    return "[ТЕЛЕФОН]" if re.fullmatch(r"(?:7|8)?9\d{9}", digits) else run


