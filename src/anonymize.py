def _pair_is_fio(a: str, b: str) -> bool:
    """Пара соседних слов с заглавной — часть ФИО?

    Две заглавные подряд сами по себе ничего не значат («Прописка
    Ставропольский», «Метро Приморская» — это адрес и станция). Нужен признак
    имени: известное имя рядом с фамильным окончанием, отчество, либо фамильное
    окончание при том, что второе слово не из предметной области и не служебное.
    """
    la, lb = a.lower(), b.lower()
    if la in NOT_NAMES_LOWER or lb in NOT_NAMES_LOWER:
        return False
    if PATRONYMIC.match(a) or PATRONYMIC.match(b):
        return True
    if (_is_given(a) and (_is_surname_like(b) or _is_oblique_surname(b))) \
            or ((_is_surname_like(a) or _is_oblique_surname(a)) and _is_given(b)):
        return True
    return _is_surname_like(a) or _is_surname_like(b)


def _mask_fio(text: str) -> str:
    """Маскирует ФИО целиком, где бы оно ни стояло в предложении.

    Идём по словам с заглавной и смотрим соседние пары: так «Банка России
    Александра Данилова» превращается в «Банка России [ИМЯ]», а не остаётся
    нетронутым из-за того, что цепочка началась с «Банка».
    """
    tokens = list(CAP_WORD.finditer(text))
    if len(tokens) < 2:
        return text
    mark = [False] * len(tokens)
    for i in range(len(tokens) - 1):
        a, b = tokens[i], tokens[i + 1]
        if not BETWEEN_NAMES.fullmatch(text[a.end():b.start()]):
            continue
        if _pair_is_fio(a.group(0), b.group(0)):
            mark[i] = mark[i + 1] = True
    if not any(mark):
        return text
    out, last, i = [], 0, 0
    while i < len(tokens):
        if not mark[i]:
            i += 1
            continue
        j = i
        while (j + 1 < len(tokens) and mark[j + 1]
               and BETWEEN_NAMES.fullmatch(text[tokens[j].end():tokens[j + 1].start()])):
            j += 1
        out.append(text[last:tokens[i].start()])
        out.append("[ИМЯ]")
        last = tokens[j].end()
        i = j + 1
    out.append(text[last:])
    return "".join(out)


def _mask_lone_surname(text: str) -> str:
    """Фамилия без имени рядом: «Клиент Семёнов», «Это Примерова».

    Два ограничения против ложных срабатываний: слово в начале предложения не
    трогаем («Причина отказа»), и слово после географического указателя тоже
    («Метро Приморская», «ЖК Северная Долина»).
    """
    out, last = [], 0
    for m in CAP_WORD.finditer(text):
        word = m.group(0)
        low = word.lower()
        if low in NOT_NAMES_LOWER or not _is_surname_like(word) or _is_given(word):
            continue
        # смотрим только хвост перед словом — иначе на длинном тексте с сотнями
        # заглавных слов копирование префикса растёт квадратично
        tail = text[max(0, m.start() - 60):m.start()]
        before = tail.rstrip()
        if not before or before[-1] in ".!?:;)»\n" or tail.endswith("\n"):
            # Начало предложения. Фамилия здесь только при явных признаках:
            # после неё запятая («Кузнецова, добрый день») или слово со
            # строчной, не географическое («Кузнецова хочет узнать»).
            # «Московская область», «Причина отказа» остаются на месте.
            nxt = re.match(r"\s*(,)|\s+([а-яё]+)", text[m.end():])
            if not nxt or len(word) < 5 or (nxt.group(2) and _is_geo(nxt.group(2))):
                continue
            # «Косметический ремонт», «Авторский надзор», «Заводской профиль» —
            # прилагательные на -ский/-ской в начале фразы фамилией не считаем
            if re.search(r"(?:ский|ская|ской|цкий|цкая|цкой)$", low):
                continue
        else:
            prev_word = before.split()[-1].strip("«»\"'()").lower()
            if prev_word in GEO_WORDS:
                continue
        # «в Московской области», «на Приморской набережной» — место, не человек
        nxt = re.match(r"\s+([а-яё]+)", text[m.end():])
        if nxt and _is_geo(nxt.group(1)):
            continue
        out.append(text[last:m.start()])
        out.append("[ИМЯ]")
        last = m.end()
    out.append(text[last:])
    return "".join(out)


def _intro_mask(m: re.Match[str]) -> str:
    """«Меня зовут Рафик Ким» — второе слово с заглавной тоже часть имени,
    если это не предметное слово: «меня зовут Ярослава, Москва» оставит Москву."""
    tail = m.group(3)
    keep = tail if tail and tail.lower() in NOT_NAMES_LOWER else None
    return m.group(1) + "[ИМЯ]" + (" " + keep if keep else "")


# Латинское имя: пара слов с заглавных рядом со словом, которое бывает только
# про человека. Один шаблон на маскировку и на проверку выхода.
_HUMAN_HINT = (r"звонил\w*|звонит|написал\w*|пишет|просил\w*|просит|сказал\w*|говорил\w*|"
               r"приезжал\w*|придёт|придет|клиент\w*|заказчик\w*|покупател\w*|собственник\w*")
# 1) пара с заглавных, после которой сказано, что это человек: «Ivan Petrov звонил»
_LATIN_NAME = re.compile(
    rf"\b[A-Z][a-z]{{2,20}}\s+[A-Z][a-z]{{2,20}}\b(?=[\s,.:;!?—-]{{1,4}}(?:{_HUMAN_HINT}))")
# 2) латинское имя сразу после указателя на человека: «клиент Ivan», «зовут Ivan Petrov»
_LATIN_AFTER_HINT = re.compile(
    r"\b((?i:клиент|клиентка|зовут|это|от|для|передайте|с уважением|mr\.?|ms\.?))"
    r"([\s,.:—-]{1,4})([A-Z][a-z]{2,20}(?:\s+[A-Z][a-z]{2,20})?)\b")


def _mask_names_live(text: str, known_names: set[str]) -> str:
    """Маскировка имён для живого текста: сообщения клиента и базы знаний.

    В отличие от корпусного режима не трогает обычные слова с заглавной буквы
    («Вторичка», «Питер», «Новостройка»): в переписке с клиентом важно, чтобы
    модель видела, что он написал. Телефоны, почта, адреса, карты и документы
    маскируются теми же правилами, что и в корпусе.
    """
    for name in sorted(known_names, key=len, reverse=True):
        if len(name) >= 3:
            text = re.sub(rf"\b{re.escape(name)}\b", "[ИМЯ]", text, flags=re.I)
    # Пара латинских слов с заглавных — имя, если рядом сказано, что это человек:
    # «Ivan Petrov звонил». Без такого признака не трогаем, иначе «Apple Pay»
    # и «Sber Bank» превращаются в [ИМЯ].
    text = _LATIN_NAME.sub("[ИМЯ]", text)
    text = _LATIN_AFTER_HINT.sub(lambda m: f"{m.group(1)}{m.group(2)}[ИМЯ]", text)
    # Слово с заглавной сразу после указателя на человека: коротких и редких
    # фамилий («Ли», «Ким», «Черных», «Мюллер») нет ни в одном словаре.
    text = re.sub(r"\b((?i:клиент|клиентка|зовут|это|от|для|передайте|передай|г-н|г-жа|"
                  r"господин|госпожа|с уважением))([\s,.:—-]{1,4})([А-ЯЁ][а-яё]{1,20}|[A-Z][a-z]{1,20})\b",
                  lambda m: (m.group(0) if (m.group(3).lower() in NOT_NAMES_LOWER or _is_geo(m.group(3)))
                             else f"{m.group(1)}{m.group(2)}[ИМЯ]"), text)
    text = NAME_INTRO.sub(_intro_mask, text)
    text = NAME_VOCATIVE.sub(
        lambda m: m.group(1) + (m.group(2) if m.group(2).lower() in NOT_NAMES_LOWER else "[ИМЯ]"),
        text)
    text = _mask_fio(text)
    text = PATRONYMIC_ALONE.sub("[ИМЯ]", text)
    text = NAME_ADDRESS.sub(
        lambda m: "[ИМЯ]" if _is_given(m.group(1)) and m.group(1).lower() not in NOT_NAMES_LOWER
        else m.group(1), text)
    text = NAME_SINGLE.sub(
        lambda m: "[ИМЯ]" if (_is_given(m.group(0))
                              and m.group(0).lower() not in NOT_NAMES_LOWER
                              and m.group(0).lower() not in AMBIGUOUS_SINGLE) else m.group(0), text)
    return _mask_lone_surname(text)


def _mask_names(text: str, known_names: set[str]) -> str:
    """Режим корпуса: всё, что умеет живой режим (известные имена, представления,
    пары имя+фамилия, отчества, словарь имён), и сверх того любое слово с
    заглавной перед запятой или восклицанием — кроме географии и слов ниши:
    «Живу в Казани, район…» остаётся, «Ковалевский, добрый день» — нет."""
    text = _mask_names_live(text, known_names)

    def call(m: re.Match[str]) -> str:
        word = m.group(1)
        low = word.lower()
        if word in NOT_NAMES or low in NOT_NAMES_LOWER:
            return word
        if _is_geo(word) and not _is_surname_like(word):
            return word
        return "[ИМЯ]"

    return NAME_CALL.sub(call, text)


def anonymize(text: str, known_names: set[str] | None = None, *, aggressive: bool = True) -> str:
    """Вычищает персональные данные без возможности восстановления.

    aggressive=True — режим корпуса: любое слово с заглавной перед запятой или
    восклицанием считается именем. Лучше замаскировать лишнее, чем пропустить.
    aggressive=False — режим живого чата: именами считаются только известные
    имена и явные представления, иначе помощник перестаёт понимать клиента.
    """
    if not text:
        return ""
    # U+2028/U+2029 и прочие экзотические разделители: JSON их не экранирует,
    # а splitlines() в Python и часть парсеров считают их переводом строки —
    # одна запись разваливается на несколько. Убираем на входе.
    out = _normalize(text.translate({0x2028: " ", 0x2029: " ", 0x0b: " ", 0x0c: " ", 0x85: " "}))
    for pattern, replacement in PATTERNS:
        out = pattern.sub(replacement, out)
    masker = _mask_names if aggressive else _mask_names_live
    out = masker(out, known_names or set())
    # схлопываем повторы вида [ТЕЛЕФОН] [ТЕЛЕФОН]
    out = re.sub(r"(\[[А-ЯЁA-Z_]+\])(\s*\1)+", r"\1", out)
    return out.strip()


