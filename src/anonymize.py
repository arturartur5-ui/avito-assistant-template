    forms: set[str] = set()
    for n in names:
        forms.add(n)
        stem = n[:-1] if n[-1] in "аяй" else n
        # Голая основа («инн» от Инны, «ян» от Яны) — не форма имени, а
        # обычное слово или аббревиатура; в набор идут только с окончанием.
        forms.update(stem + suf for suf in _CASE_SUFFIXES if suf or stem == n)
    return forms


