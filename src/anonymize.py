_MOSTLY_DIGITS = re.compile(rf"(?<![^\W\d_])[{_LOOKALIKE_CHARS}][{_LOOKALIKE_CHARS}*,:;.\-/()\[\]_ ]{{5,}}"
                            rf"[{_LOOKALIKE_CHARS}](?![^\W\d_])")


def _fix_digit_lookalikes(text: str) -> str:
    """Буквы вместо цифр — только внутри того, что и так почти целиком цифры.

    «8 9OO 123 45 67» станет номером, а «взнос 600 000» и «мой OZON» не
    пострадают: группа должна начинаться и заканчиваться цифрой, не касаться
    букв по краям и состоять из цифр минимум на три четверти.
    """
    def fix(m: re.Match[str]) -> str:
        tok = m.group(0)
        body = re.sub(r"[^\w]", "", tok)
        digits = sum(c.isdigit() for c in body)
        if len(body) >= 9 and digits >= len(body) * 0.75:
            return tok.translate(_DIGIT_LOOKALIKE)
        return tok

    return _MOSTLY_DIGITS.sub(fix, text)


def _normalize(text: str) -> str:
    """Мягкая: для маскировки. Текст остаётся читаемым — он уйдёт модели.

    Убирает только невидимые знаки и чинит буквы-подмены внутри цифровых
    групп. NFKC здесь нельзя: он превращает «№» в «No», а полноширинные
    знаки — в обычные, и текст клиента меняется без нужды.
    """
    if not text:
        return ""
    return _fix_digit_lookalikes(text.translate(_INVISIBLE))


def _normalize_hard(text: str) -> str:
    """Жёсткая: только для проверки на выходе.

    Результат никому не показывается, поэтому можно искажать как угодно:
    NFKC разворачивает полноширинные цифры и верхние индексы, после чего
    подмены букв ищутся ещё раз.
    """
    if not text:
        return ""
    return _fix_digit_lookalikes(unicodedata.normalize("NFKC", text.translate(_INVISIBLE)))


def _numerals_to_digits(text: str) -> str:
    """«восемь девятьсот двенадцать» → «8 900 12»: для поиска номера словами."""
    return _NUMERAL_RX.sub(lambda m: _NUMERALS[m.group(1).lower()], text)


def _phone_run(m: re.Match[str]) -> str:
    """Подчищающее правило для телефонов в непредусмотренном написании.

    Любая цепочка из 10–11 цифр с какими угодно разделителями, если после
    склейки она выглядит как российский мобильный (9xx…). Диапазоны сумм
    «50 000 - 100 000» не трогаем: у них дефис с пробелами по бокам.
    """
    run = m.group(0)
    if _DASH_SPACED.search(run):
        return run
    digits = re.sub(r"\D", "", run)
    return "[ТЕЛЕФОН]" if re.fullmatch(r"(?:7|8)?9\d{9}", digits) else run


