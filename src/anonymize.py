# Дата в любом ходовом написании. Нужна, чтобы «цепочка цифр» не считала
# утечкой «Годен до: 22.10.2026» и тег куска «[диалог, 2025-06-15]»: телефон
# и номер документа в такую форму не укладываются (там 10–20 цифр подряд),
# а дата — обычная часть условий, корпуса и любого делового текста.
_DATE_LIKE = re.compile(
    r"^(?:"
    r"\d{1,2}[./\-]\d{1,2}[./\-]\d{2,4}"          # 22.10.2026, 5/3/24
    r"|\d{4}[./\-]\d{1,2}[./\-]\d{1,2}"           # 2025-06-15
    r"|\d{1,2}[./\-]\d{4}"                         # 10.2026
    r")$")


_MONTHS_LIKE = re.compile(r"^\d{1,2}[./]\d{4}(?:\s*[,;–-]\s*\d{1,2}[./]\d{4})+$")   # 12.2025, 01.2026
# Диапазон сумм: «850 000 - 1 100 000», «800 000-900 000». Самая частая фраза
# про деньги — без этого помощник молчал на каждом разговоре о бюджете.
_RANGE_LIKE = re.compile(r"^\d{1,3}(?:[ \u00a0]\d{3})*(?:[.,]\d{1,2})?\s*[-–—]\s*"
                         r"\d{1,3}(?:[ \u00a0]\d{3})*(?:[.,]\d{1,2})?$")
# Числа, соединённые словом: «12.5000 и 8.2500», «30 / 40 / 30» — перечисление,
# а не одна цепочка.
_LIST_LIKE = re.compile(r"^\d[\d.,]*(?:\s*(?:[,;/]|\bи\b|\bили\b)\s*\d[\d.,]*)+$")
_AMOUNT_LIKE = re.compile(r"^\d{1,3}(?:[ .\u00a0]\d{3})+(?:[,.]\d{2})?$")          # 1 250 000,00
_TIME_LIKE = re.compile(r"^\d{1,2}:\d{2}(?::\d{2})?(?:\s*[-–]\s*\d{1,2}:\d{2}(?::\d{2})?)?$")
_DATE_TIME_LIKE = re.compile(r"^(?:\d{4}-\d{2}-\d{2}|\d{1,2}[./]\d{1,2}[./]\d{2,4})(?:[ T,]+\d{1,2}:\d{2}(?::\d{2})?)?$"
                             r"|^\d{1,2}[./]\d{1,2}[./]\d{2,4}\s*[-–]\s*\d{1,2}[./]\d{1,2}[./]\d{2,4}$")
_NOT_PERSONAL_BEFORE = re.compile(r"(?:№|\bN[o0]\b|\bТУ\b|заказ\w*|договор\w*|заявк\w*|артикул\w*|ДДУ|ГОСТ|СНиП|\bСП\b|БИК|ОКПО|ОКВЭД|КПП|ОГРН\b|лот\w*|полис\w*|"
                                  r"объявлени\w*|\bID\b|код\s+товара|сч[её]т-фактур\w*)\s*[:#№]?\s*$", re.I)


def _not_a_date(value: str) -> bool:
    """Находка «цепочка цифр» — действительно номер, а не дата?"""
    return not _DATE_LIKE.match(value.strip())


def _is_list(value: str) -> bool:
    """Перечисление чисел («30 / 40 / 30», «12.5 и 8.25») — или номер через «и»?

    Телефон, надиктованный через «и», выглядит так же, поэтому решает число
    цифр: десять и больше при четырёх и более группах — это номер.
    """
    if not _LIST_LIKE.match(value):
        return False
    digits = sum(c.isdigit() for c in value)
    groups = len(re.findall(r"\d[\d.,]*", value))
    return not (digits >= 10 and groups >= 4)


def _months_pair(value: str) -> bool:
    return bool(_MONTHS_LIKE.match(value.strip()))


def _chain_is_suspect(m: re.Match[str]) -> bool:
    """Цепочка цифр — телефон/документ, а не сумма, дата, время или номер договора.

    Ложная тревога здесь — молчание помощника на «1 250 000 рублей», поэтому
    привычные деловые формы отсеиваются явно.
    """
    v = m.group(0).strip()
    if (_DATE_LIKE.match(v) or _AMOUNT_LIKE.match(v) or _TIME_LIKE.match(v)
            or _DATE_TIME_LIKE.match(v) or _MONTHS_LIKE.match(v)
            or _RANGE_LIKE.match(v) or _is_list(v)):
        return False
    before = m.string[max(0, m.start() - 24):m.start()]
    if _NOT_PERSONAL_BEFORE.search(before):
        return False
    return True


