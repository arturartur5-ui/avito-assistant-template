# Дверь наружу
#
# Всё, что уходит с российского сервера к модели, проходит через outbound():
# сообщение клиента, история диалога, куски базы знаний, файл условий. Одна
# функция — одно место, где можно ошибиться, и одно место, которое проверяется.
# ---------------------------------------------------------------------------

OWNER_ROLE = "специалист"


@functools.lru_cache(maxsize=1)
def _owner_rx() -> re.Pattern[str] | None:
    """Имя владельца аккаунта из OWNER_NAME_FORMS: «Ярополк,Ярик,Примеров» → основы.

    Самих имён в коде нет — только переменная окружения, поэтому файл
    переносится в blueprint без персональных данных.
    """
    stems = [x.strip() for x in os.environ.get("OWNER_NAME_FORMS", "").split(",") if x.strip()]
    if not stems:
        return None
    alt = "|".join(re.escape(x) + r"\w*" for x in stems)
    # Подряд идущие формы («Ярополк Примеров») схлопываются в одно слово.
    return re.compile(rf"(?:\b(?:{alt})\b[\s\-]*)+", re.I)


def mask_owner(text: str) -> str:
    rx = _owner_rx()
    if not (rx and text):
        return text
    out = rx.sub(OWNER_ROLE + " ", text)
    out = re.sub(r"[ \t]{2,}", " ", out)
    return re.sub(r"\s+([,.;:!?)])", r"\1", out).strip()


def outbound(text: str) -> str:
    """Обезличивание всего, что покидает российский сервер."""
    if not text:
        return ""
    return anonymize(mask_owner(text), aggressive=False)


# Проверка на выходе: то же, что маскирует outbound(), но в виде поиска.
# Если тут что-то нашлось — значит какой-то кусок обошёл дверь.
EGRESS_CHECKS: list[tuple[str, re.Pattern[str]]] = [
    ("почта", re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b")),
    ("ник", re.compile(r"(?<![\w@])@[A-Za-zА-Яа-яЁё]\w{2,}")),
    ("паспорт", re.compile(r"\b\d{4}[\s.\-№:]{0,3}\d{6}\b")),
    ("СНИЛС", re.compile(r"\b\d{3}[\s.\-]\d{3}[\s.\-]\d{3}[\s.\-]\d{2}\b")),
    ("карта", re.compile(r"\b(?:\d{4}[\s.\-\u2011\u2013]?){3}\d{4}\b")),
    ("ссылка", re.compile(rf"https?://\S+|(?<![\w@/.])(?!дом\.рф)(?:[a-zа-яё0-9-]+\.)+(?:{TLDS})(?:/\S*)?(?!\.?\w)"
                          r"|(?<![\w@/.])[a-zа-яё0-9-]+\.[a-zа-яё]{2,6}/\S+", re.I)),
    ("телефон", re.compile(r"(?:\+7|\b8)[\s\-()]*\d{3}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}\b"
                           r"|\b[78]\d{10}\b|\b9\d{9}\b")),
    ("длинное число", re.compile(r"(?<![\d.,])\d{10,}(?![\d.,])")),
    ("отчество", PATRONYMIC_ALONE),
    ("координаты", _COORD_RX),
    ("имя латиницей", re.compile(r"\b(?i:my name is|my name's|i am|i'm|this is|call me)\s+"
                                 r"[A-Z][a-z]{1,20}\b")),
    ("имя после «я»", re.compile(r"(?<![\w])[Яя]\s+[А-ЯЁ][а-яё]{1,20}"
                                 r"(?=\s*[,.!?]|\s+(?:живу|проживаю|работаю|из|с\b))")),
]


# Подозрительные формы для проверки на выходе. Здесь правила нарочно шире, чем
# в маскировке: ложная тревога стоит одного молчания помощника, пропуск —
# персональных данных за границей.
_SUSPECT: list[tuple[str, re.Pattern[str]]] = [
    # длинная цепочка цифр с любыми разделителями: номер, счёт, документ
    ("цепочка цифр", re.compile(r"(?<![\d.,])\d(?:[\s*,:;.\-/()\[\]_‑‒–—−]{0,3}\d){6,}(?![\d.,])")),
    # ↑ проверяется через _not_a_date(): дата — не номер документа
    # координаты в любой записи, включая градусы и N/E
    ("координаты", re.compile(r"\d{1,3}[.,]\d{4,8}\s*[,;]?\s*[NSEWнвсю]?\s*[,;]?\s*\d{1,3}[.,]\d{4,8}"
                              r"|\d{1,3}°\d{1,2}'[\d.]*[\"″]?\s*[NSEW]")),
    # почта и ссылка, записанные словами или в скобках
    ("почта словами", re.compile(r"[\w.+-]{2,}\s*(?:@|＠|\(at\)|\[at\]|\bсобака\b|\bat\b)\s*[\w-]{2,}"
                                 r"\s*(?:\.|\(dot\)|\[dot\]|\bточка\b|\bdot\b)\s*[a-zа-я]{2,}", re.I)),
    ("домен словами", re.compile(r"(?i)\b(?:сайт|site|hxxps?|профиль)\b\s*:?\s*"
                                 r"[a-zа-я0-9-]{2,}\s*(?:\.|\[\.\]|\(dot\)|\bточка\b|,)\s*[a-zа-я]{2,10}\b")),
    # ник после названия площадки, без собаки
    ("ник", re.compile(r"(?i)\b(?:инст\w*|инстаграм|тикток|вк\b|vk\b|ютуб\w*|дискорд|тг\b|тгк\b|"
                       r"телег\w*|вотс\w*|вотц\w*|ватс\w*|whats\w*|скайп|skype)\b\s*:?\s*"
                       r"[@]?[A-Za-z][A-Za-z0-9_.-]{3,30}")),
    ("профиль id", re.compile(r"(?i)\bid\s*:?\s*\d{5,}")),
    # документы и номера с любыми разделителями
    ("паспорт", re.compile(r"(?i)\bсери[яи]\b[^\d]{0,6}\d{2}\s?\d{2}[^\d]{0,12}\d{6}")),
    ("кадастровый номер", re.compile(r"\b\d{2}:\d{2}:\d{6,7}:\d+\b")),
    ("VIN", re.compile(r"\b(?=[A-HJ-NPR-Z0-9]{17}\b)(?=[A-HJ-NPR-Z0-9]*\d)[A-HJ-NPR-Z0-9]{17}\b")),
    ("госномер", re.compile(r"\b[АВЕКМНОРСТУХ]\s?\d{3}\s?[АВЕКМНОРСТУХ]{2}\s?\d{2,3}\b")),
    # имя латиницей — только там, где рядом сказано, что речь о человеке:
    # иначе «Apple Pay» и «Sber Bank» заставляли бы помощника молчать
    ("имя латиницей", _LATIN_NAME),
    ("имя латиницей", _LATIN_AFTER_HINT),
    # дата рождения словами и в других записях
    ("дата рождения", re.compile(r"(?i)(?:родил\w*|рожден\w*|дата\s+рождения|д\.\s?р\.)[\s:—-]{0,4}"
                                 r"(?:\d{1,2}\s+\w+\s+\d{4}|\d{4}-\d{2}-\d{2}|\d{2}[./]\d{2}[./]\d{2,4})")),
]


# Дата в любом ходовом написании. Нужна, чтобы «цепочка цифр» не считала
# утечкой «Годен до: 22.10.2026» и тег куска «[диалог, 2025-06-15]»: телефон
# и номер документа в такую форму не укладываются (там 10–20 цифр подряд),
# а дата — обычная часть условий, корпуса и любого делового текста.
_DATE_LIKE = re.compile(
    r"^(?:"
    r"\d{1,2}[./\-]\d{1,2}[./\-]\d{2,4}"          # 22.10.2026, 5/3/24
    r"|\d{4}[./\-]\d{1,2}[./\-]\d{1,2}"           # 2025-06-15
    r"|\d{1,2}[./\-]\d{4}"                         # 10.2026
    r")$")


def _not_a_date(value: str) -> bool:
    """Находка «цепочка цифр» — действительно номер, а не дата?"""
    return not _DATE_LIKE.match(value.strip())


def leak_scan(text: str) -> list[tuple[str, str]]:
    """Что подозрительного осталось в тексте. Пусто — значит можно отправлять.

    Эта проверка НЕ повторяет правила маскировки, а намеренно шире их: она
    последняя перед отправкой за границу, и её находка означает «не отправлять»
    (см. Engine._egress_check). Поэтому здесь ловятся и формы, которые
    маскировка не умеет чистить, — их увидит специалист, а не модель.
    """
    if not text:
        return []
    norm = _normalize_hard(text)
    # то же, но числительные словами переведены в цифры: «восемь девятьсот…»
    spelled = _numerals_to_digits(norm)

    found = [(name, m.group(0)) for name, rx in EGRESS_CHECKS for m in rx.finditer(norm)]
    found += [(name, m.group(0)) for name, rx in _SUSPECT for m in rx.finditer(norm)
              if name != "цепочка цифр" or _not_a_date(m.group(0))]
    # цепочка цифр, собранная из числительных: ищем только там, где слов-числительных много
    if len(_NUMERAL_RX.findall(norm)) >= 4:
        for name, rx in _SUSPECT[:1]:
            found += [("номер словами", m.group(0)) for m in rx.finditer(spelled)]
    found += [("телефон", m.group(0)) for m in _DIGIT_RUN.finditer(norm)
              if _phone_run(m) != m.group(0)]
    rx = _owner_rx()
    if rx:
        found += [("имя владельца", m.group(0)) for m in rx.finditer(norm)]
    return found


PLACEHOLDER = re.compile(r"\[(?:ИМЯ|ТЕЛЕФОН|EMAIL|АДРЕС|КАРТА|СНИЛС|ИНН|ПАСПОРТ|"
                         r"ССЫЛКА|НИК|НОМЕР|ДАТА)\]")


def split_names(raw: str) -> set[str]:
    """Из «Ярослава Примерова - специалист по чему-то» достаёт имя и фамилию."""
    parts = re.split(r"[\s\-—,]+", raw or "")
    return {p for p in parts if p.isalpha() and len(p) > 2 and p[0].isupper()}


