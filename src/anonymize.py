# Разделители внутри номера: пробел, точка, дефис, слеш, скобки и все «дефисы»
# юникода — номер, скопированный с экрана телефона, часто приходит с неразрывным
# дефисом (U+2011) или коротким тире, и обычный класс [\s\-()] его не видит.
# Доменные зоны, которые считаем ссылкой. Одна константа на обезличивание и
# фильтр исходящих: списки разъезжались, и t.me/… проходил.
TLDS = ("ru|com|рф|net|org|su|me|io|app|pro|online|site|ph|biz|info|xyz|link|cc|gl|ly|tv|"
        "club|shop|store|dev|ai|kz|by|ua|uz")
_SEP_CHARS = r"\s.\-/()\[\]_‑‒–—−*,:;#+'~\\·•«»"
_SEP = f"[{_SEP_CHARS}]"
# То же без перевода строки: иначе склеиваются два разных числа с соседних строк.
_SEP_NB = r"[ .\-/()\[\]_‑‒–—−*,:;#+'~\\·•«»]"
_DASH_SPACED = re.compile(r"\s[\-‑‒–—−]\s")


# Невидимые знаки: их вставляют между цифрами, чтобы номер не опознался.
