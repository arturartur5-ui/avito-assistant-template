def leak_scan(text: str) -> list[tuple[str, str]]:
    """Что подозрительного осталось в тексте. Пусто — значит можно отправлять.

    Эта проверка НЕ повторяет правила маскировки, а намеренно шире их: она
    последняя перед отправкой за границу, и её находка означает «не отправлять»
    (см. Engine._egress_check). Поэтому здесь ловятся и формы, которые
    маскировка не умеет чистить, — их увидит специалист, а не модель.
    """
    if not text:
        return []
    norm = _normalize_hard(text)
    # то же, но числительные словами переведены в цифры: «восемь девятьсот…»
    spelled = _numerals_to_digits(norm, mark=True)

    # Классы, которые бывают номером заказа, договора или объявления: если слева
    # об этом прямо сказано, тревоги нет — иначе помощник молчит на «номер заказа».
    _DOC_LIKE = {"паспорт", "длинное число", "ИНН", "карта"}
    found = [(name, m.group(0)) for name, rx in EGRESS_CHECKS for m in rx.finditer(norm)
             if name not in _DOC_LIKE
             or not _NOT_DOC_BEFORE.search(norm[max(0, m.start() - 26):m.start()])]
    for name, rx in _SUSPECT:
        for m in rx.finditer(norm):
            if name == "цепочка цифр" and not _chain_is_suspect(m):
                continue
            if name == "координаты" and m.re.groups >= 2 and (_coords(m) == m.group(0) or _months_pair(m.group(0))):
                continue
            if name == "имя вне словаря":
                w = m.group(1)
                low = w.lower()
                if (low in NOT_NAMES_LOWER or _is_geo(w) or low in _ROLE_WORDS
                        or low in _NOT_A_NAME_START):
                    continue
            found.append((name, m.group(0)))
    # номер, собранный из числительных: цепочка должна содержать хотя бы две
    # метки замены — иначе дата рядом со словами «один раз» становилась «номером»
    for m in _CHAIN_SPELLED.finditer(spelled):
        if m.group(0).count(_NUMERAL_MARK) >= 2 and _chain_is_suspect(m):
            found.append(("номер словами", m.group(0).replace(_NUMERAL_MARK, "")))
    found += [("телефон", m.group(0)) for m in _DIGIT_RUN.finditer(norm)
              if _phone_run(m) != m.group(0)]
    rx = _owner_rx()
    if rx:
        found += [("имя владельца", m.group(0)) for m in rx.finditer(norm)]
    return found


