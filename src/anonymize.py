# Слова, после которых длинное число — не документ, а номер заказа, договора,
# объявления, лота. Их клиент присылает постоянно, и модель должна их видеть.
_NOT_DOC_BEFORE = re.compile(
    r"(?i)(?:№|\bN[o0]\b|заказ\w*|договор\w*|заявк\w*|артикул\w*|объявлени\w*|лот\w*|"
    r"полис\w*|накладн\w*|сч[её]т[-\w]*|фактур\w*|ДДУ|отправлени\w*|трек\w*|\bID\b|"
    r"номер\s+(?:заказ|договор|объявлен|заявк|лот|телефон)\w*)\s*[:#№-]?\s*$")


def _card_or_order(m: re.Match[str]) -> str:
    """16 цифр — карта, если слева не сказано «объявление», «заказ», «лот»."""
    if _NOT_DOC_BEFORE.search(m.string[max(0, m.start() - 26):m.start()]):
        return m.group(0)
    return "[КАРТА]"


def _order_number_or_mask(m: re.Match[str]) -> str:
    """Длинное число: номер документа — или номер заказа, если слева так сказано."""
    if _NOT_DOC_BEFORE.search(m.string[max(0, m.start() - 26):m.start()]):
        return m.group(0)
    return "[НОМЕР]"


def _passport_or_order(m: re.Match[str]) -> str:
    """4+6 цифр — паспорт, если слева не сказано «заказ», «артикул», «договор»."""
    if _NOT_DOC_BEFORE.search(m.string[max(0, m.start() - 26):m.start()]):
        return m.group(0)
    return "[ПАСПОРТ]"


def _order_number(m: re.Match[str]) -> str:
    """Десять цифр подряд: ИНН — или номер заказа, если слева сказано какой."""
    if _NOT_DOC_BEFORE.search(m.string[max(0, m.start() - 26):m.start()]):
        return m.group(0)
    return "[ИНН]"


_order_number_guard = re.compile(r"(?<![\d.,])\b\d{10}\b(?!\d|[.,]\d)")


def _bare_street(m: re.Match[str]) -> str:
    """«Ленина 5 кв 12» — улица без слова «улица». Город и обычное слово не трогаем."""
    word = m.group(1)
    low = word.lower()
    if low in GEO_WORDS or low in NOT_NAMES_LOWER or low in _NOT_STREET:
        return m.group(0)
    return "[АДРЕС]"


def _bare_address(m: re.Match[str]) -> str:
    """«живу на Невского 15» — адрес без слова «улица».

    Город адресом не считаем: «живу в Самаре 5 лет» — это не место жительства
    с точностью до дома. Проверка по словарю географии, а не по форме слова.
    """
    place = m.group(2)
    if _is_geo(place) or place.lower() in NOT_NAMES_LOWER:
        return m.group(0)
    return f"{m.group(1)} [АДРЕС]"

