def _coords(m: re.Match[str]) -> str:
    """Пара чисел — координата или два обычных числа рядом?

    Координатой считаем только правдоподобную пару: широта до 90, долгота до
    180 и хотя бы одно число вне диапазона оценок и процентов. Иначе «рейтинг
    4.9876 5.0000» и «ставка 12.5000 8.2500» уезжали бы в [КООРДИНАТЫ].
    """
    try:
        lat, lon = abs(float(m.group(1))), abs(float(m.group(2)))
    except ValueError:
        return m.group(0)
    if lat > 90 or lon > 180:
        return m.group(0)
    if lat <= 20 and lon <= 20:          # обе маленькие — это оценки, доли, ставки
        return m.group(0)
    return "[КООРДИНАТЫ]"


def _me_name(m: re.Match[str]) -> str:
    """«Я Ким» → «Я [ИМЯ]»: регистр местоимения сохраняем, как написал клиент."""
    return f"{m.group(1)} [ИМЯ]"


