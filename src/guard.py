DRAFT_MESSENGER = _n("DRAFT_MESSENGER", "Хорошо, как вам удобно. Вернусь к вам чуть позже с ответом.")
DRAFT_POLITICS = _n("DRAFT_POLITICS", "Давайте по делу — расскажите, что именно вам нужно?")
# «Вы бот?» — не да и не нет, и разговор специалисту.
DRAFT_BOT_QUESTION = _n("DRAFT_BOT_QUESTION", "Я здесь, читаю ваши сообщения. Подскажите, какой у вас вопрос?")
# Направления, которыми специалист не занимается: config/niche.py → NOT_OUR_WORK.
NOT_OUR_WORK: list[tuple[str, str]] = _n("NOT_OUR_WORK", [])
DRAFT_NOT_OUR_WORK = _n("DRAFT_NOT_OUR_WORK", "Этим направлением я не занимаюсь.")

# Откуда у специалиста деньги: «сколько вам платит партнёр», «вы откат берёте».
