# Отрицание перед обещанием переворачивает смысл: «не могу гарантировать
# одобрение» — это как раз правильный ответ, придерживать его нельзя.
# Смотрим окно слева от совпадения.
NEGATION = re.compile(
    r"(?:\bне\b|\bнельзя\b|\bникто\b|\bневозможно\b|\bни\s+один\b|"
    r"\bне\s+могу\b|\bне\s+может\b|\bне\s+бывает\b|\bнет\b)",
    re.I,
)
NEGATION_WINDOW = 60

# Отрицание бывает и справа: «100% гарантии дать не могут». Здесь список узкий —
# только глаголы невозможности, иначе «не переживайте» сойдёт за отрицание.
NEGATION_AFTER = re.compile(
    r"\bне\s+(?:мог\w*|может|можем|дад\w*|дать|бывает|получ\w*|гарантир\w*|"
    r"обещ\w*|стоит)",
    re.I,
)
NEGATION_AFTER_WINDOW = 80


# Разрядка («в о т с а п»), буквы вместо цифр и невидимые знаки — способ обойти
# фильтр, который на площадке применяют постоянно. Перед проверкой текст
# приводится к обычному виду тем же кодом, что и обезличивание.
_SPACED_OUT = re.compile(r"\b(?:[а-яёa-z]\s){2,}[а-яёa-z]\b", re.I)


def _normalize_for_check(text: str) -> str:
    """Текст для поиска правил: слитно то, что растянули по буквам."""
    out = _anon_normalize(text)
    return _SPACED_OUT.sub(lambda m: m.group(0).replace(" ", ""), out)


def _negated(text: str, start: int, end: int) -> bool:
    """Отрицание снимает обещание, только если между ними нет знака препинания:
    «не могу гарантировать одобрение» — да; «не переживайте, вам точно одобрят» — нет."""
    left = text[max(0, start - NEGATION_WINDOW):start]
    last = None
    for last in NEGATION.finditer(left):
        pass
    if last and not re.search(r"[,.!?;:]", left[last.end():]):
        return True
    right = text[end:end + NEGATION_AFTER_WINDOW]
    m = NEGATION_AFTER.search(right)
    return bool(m and not re.search(r"[,.!?;:]", right[:m.start()]))


