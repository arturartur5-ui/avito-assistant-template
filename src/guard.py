def check_incoming(text: str) -> Verdict:
    """Проверка вопроса клиента: нелегальное отметаем, остальные поводы — к специалисту."""
    if not text:
        return Verdict(SEND)
    # клиент обходит фильтр площадки теми же приёмами: разрядкой, буквами
    # вместо цифр, невидимыми знаками — выпрямляем перед проверкой
    text = _normalize_for_check(text)
    illegal = sorted({name for rx, name in _COMPILED_ILLEGAL if rx.search(text)})
    if illegal:
        return Verdict(HOLD, "нелегальный запрос клиента", illegal, DRAFT_ILLEGAL)
    reasons = {name for rx, name in _COMPILED_ESCALATE_IN if rx.search(text)}
    if any(_phone_run(m) != m.group(0) for m in _DIGIT_RUN.finditer(text)):
        reasons.add("оставил контакт")
    # номер, записанный словами: «восемь девятьсот двенадцать…»
    if len(re.findall(r"\b(?:ноль|один|два|три|четыре|пять|шесть|семь|восемь|девять|десять|"
                      r"двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|восемьдесят|"
                      r"девяносто|сто|двести|триста|четыреста|пятьсот|шестьсот|семьсот|"
                      r"восемьсот|девятьсот)\b", text, re.I)) >= 4:
        reasons.add("оставил контакт")
    reasons = sorted(reasons)
    if reasons:
        rs = set(reasons)
        if "политика" in rs:
            draft = DRAFT_POLITICS
        elif "спросил, не бот ли" in rs:
            draft = DRAFT_BOT_QUESTION
        elif "не наше направление" in rs:
            draft = DRAFT_NOT_OUR_WORK
        elif rs <= {"просит другой мессенджер", "оставил контакт"}:
            draft = DRAFT_MESSENGER
        else:
            draft = DRAFT_HANDOFF
        return Verdict(HOLD, "повод передать разговор", reasons, draft)
    return Verdict(SEND)


def explain(v: Verdict) -> str:
    """Человекочитаемое пояснение — то, что увидит специалист в уведомлении."""
    if v.ok:
        return "Можно отправлять."
    return (f"Не отправлено: {v.category} ({', '.join(v.reasons)}).\n"
            f"Предлагаемый ответ:\n{v.draft}" if v.draft else
            f"Не отправлено: {v.category} ({', '.join(v.reasons)}).")
