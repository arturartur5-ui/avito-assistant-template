# Расчёты, которые делает только человек: смета, платёж, срок. Модель считает
# «в уме», клиент запоминает цифру как обещание. config/niche.py → CALC_IN_REPLY.
PAYMENT_RULES: list[tuple[str, str]] = _n("CALC_IN_REPLY", [])
# «доход 200 тысяч в месяц» — это про заработок клиента, а не про платёж.
INCOME_NEAR = re.compile(r"доход|зарплат|\bзп\b|выручк|оборот|получа\w+|заработ|поступлен|прибыл|"
                         r"подтвержда\w+|стоимост\w+\s+объект", re.I)

# Остаток обезличивания в ответе: «[ИМЯ], подскажите…». Восстановить настоящее
# слово нельзя (обезличивание необратимое), поэтому такой ответ не отправляем.
PLACEHOLDER_LEFT = re.compile(r"\[(?:ИМЯ|ТЕЛЕФОН|EMAIL|АДРЕС|КАРТА|СНИЛС|ИНН|ПАСПОРТ|"
                              r"ССЫЛКА|НИК|НОМЕР|ДАТА)\]")

# Цена услуг. Правило специалиста: цены не звучат, пока диалог не
# дошёл до договора, а это решает сам специалист. Модель цен в контексте не
# получает; фильтр ловит, если она вспомнит их из примеров переписок.
_SERVICE_WORDS = re.compile(r"услуг|сопровожд|ведени|договор|оплат|стоим|цен[аыу]|работ[аыу]|"
                            r"консультац|комисси|предоплат", re.I)
_THOUSANDS = re.compile(r"\b(?:от\s+)?\d{2,3}\s*(?:тыс|000\b|т\.\s?р|\.\d{3}\b|\s*к\b)"
                        r"|\b(?:десять|двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|"
                        r"восемьдесят|девяносто|сто|двести|триста)\s+тысяч\w*", re.I)
PRICE_RULES: list[tuple[str, str]] = [
    (r"предоплат\w*", "предоплата"),
    (r"(?:стоимост\w*|цен[аыу]|стоит|стоят|обойд[её]тся)\s+(?:моих|наших|ваших)?\s*"
     r"(?:услуг\w*|сопровожден\w*|ведени[ея]|работ[аы])", "стоимость услуг словами"),
    (r"для\s+вас\s+(?:вс[её]\s+)?бесплатно|бесплатно\s*[—-]\s*комисси", "цена «бесплатно»"),
    # доля от сделки — та же цена услуг, только в процентах
    (r"\d+(?:[.,]\d+)?\s*%\s*(?:от|с)\s+(?:суммы|сделки|кредита|стоимости|контракта)|"
     r"(?:беру|возьму|работаю\s+за)\s+\d+(?:[.,]\d+)?\s*%", "доля от суммы"),
]
DRAFT_PRICE = _n("DRAFT_PRICE",
                 "Чтобы мне корректно ответить на вопрос о стоимости, нужно понять ваш запрос "
                 "более детально. Расскажите, пожалуйста, подробно вашу ситуацию.")


def _price_hits(text: str) -> list[str]:
    hits = {name for rx, name in _COMPILED_PRICE if rx.search(text)}
    for sentence in re.split(r"(?<=[.!?…])\s+|\n+", text):
        for m in _THOUSANDS.finditer(sentence):
            # «доход наличными 90 тысяч», «зарплата 120 тысяч» — про клиента, не про услуги
            if INCOME_NEAR.search(sentence[max(0, m.start() - 45):m.start()]):
                continue
            if _SERVICE_WORDS.search(sentence):
                hits.add("сумма за услуги")
    return sorted(hits)


@functools.lru_cache(maxsize=1)
def _owner_name_rules() -> tuple[re.Pattern | None, re.Pattern | None]:
    """Имя владельца в третьем лице — тоже раскрытие («передам Ярополку»).

    Основы имени берутся из .env: OWNER_NAME_FORMS=Ярополк,Ярик (через запятую),
    чтобы в коде не было персональных данных. Представление «меня зовут …»
    и подпись «…, мастер по ремонту» — не раскрытие; слова роли — в
    config/niche.py → OWNER_ROLE_WORDS, иначе общий список.
    """
    stems = [s.strip() for s in os.environ.get("OWNER_NAME_FORMS", "").split(",") if s.strip()]
    if not stems:
        return None, None
    names = "|".join(re.escape(s) + r"\w*" for s in stems)
    third = re.compile(rf"(?<![а-яё])(?:{names})(?![а-яё])", re.I)
    roles = _n("OWNER_ROLE_WORDS", r"специалист|мастер|юрист|риелтор|брокер|врач|консультант|бухгалтер|"
                                   r"дизайнер|репетитор|прораб|психолог|агент")
    intro = re.compile(rf"(?:зовут|я)\s+[—-]?\s*(?:{names})|(?:{names})\s*[,—-]\s*(?:[а-яё-]+\s+)?(?:{roles})", re.I)
    return third, intro


_COMPILED_CONTACT = [(re.compile(p, re.I), name) for p, name in CONTACT_RULES]
_COMPILED_ILLEGAL = [(re.compile(p, re.I), name) for p, name in ILLEGAL_RULES]
_COMPILED_GUARANTEE = [(re.compile(p, re.I), name) for p, name in GUARANTEE_RULES]
_COMPILED_BANKS = [(re.compile(p, re.I), name) for p, name in FORBIDDEN_NAMES]
_COMPILED_IDENTITY = [(re.compile(p, re.I), name) for p, name in IDENTITY_RULES]
_COMPILED_PRICE = [(re.compile(p, re.I), name) for p, name in PRICE_RULES]
_COMPILED_PAYMENT = [(re.compile(p, re.I), name) for p, name in PAYMENT_RULES]


def _payment_hits(text: str) -> list[str]:
    """Цифры платежа в ответе. Доход клиента, названный им самим, не считается."""
    hits = set()
    for rx, name in _COMPILED_PAYMENT:
        for m in rx.finditer(text):
            if INCOME_NEAR.search(text[max(0, m.start() - 45):m.start()]):
                continue
            hits.add(name)
    return sorted(hits)


def has_price(text: str) -> bool:
    """Есть ли в тексте цена услуг. Нужна движку, чтобы не отдать цены раньше срока."""
    return bool(_price_hits(text))


def check_outgoing(text: str, allow_price: bool = False, allow_payment: bool = False) -> Verdict:
    """Проверка ответа бота ПЕРЕД отправкой клиенту.

    allow_price=True — картина по клиенту собрана целиком, на этой стадии
    специалист цены называет, поэтому категория «цена услуг» не применяется.
    """
    if not text or not text.strip():
        return Verdict(HOLD, "пусто", ["пустой ответ"])

    # «в о т с а п», «8 9OO …», нулевая ширина — правила ищем по выпрямленному
    # тексту, а клиенту уходит оригинал
    text = _normalize_for_check(text)

    illegal = sorted({name for rx, name in _COMPILED_ILLEGAL if rx.search(text)})
    if illegal:
        return Verdict(HOLD, "нелегальное", illegal, DRAFT_ILLEGAL)

    # Обещание результата ищем только там, где нет законного употребления
    # слова «гарантия»: банковская гарантия и гарантия возврата — не обещание.
    without_allowed = GUARANTEE_ALLOW.sub(" ", text)
    promises = set()
    for rx, name in _COMPILED_GUARANTEE:
        for m in rx.finditer(without_allowed):
            if not _negated(without_allowed, m.start(), m.end()):
                promises.add(name)
    promises = sorted(promises)
    if promises:
        return Verdict(HOLD, "обещание результата", promises, DRAFT_GUARANTEE)

    if any(rx.search(text) for rx, _ in _COMPILED_BANKS):
        return Verdict(HOLD, "внутренняя кухня", ["то, что не раскрываем"], DRAFT_FORBIDDEN)

    contact = {name for rx, name in _COMPILED_CONTACT if rx.search(text)}
    if any(_phone_run(m) != m.group(0) for m in _DIGIT_RUN.finditer(text)):
        contact.add("телефон в любом написании")
    contact = sorted(contact)
    if contact:
        return Verdict(HOLD, "контакты / увод с Авито", contact, DRAFT_CONTACT)

    if PLACEHOLDER_LEFT.search(text):
        return Verdict(HOLD, "остаток обезличивания",
                       sorted({m.group(0) for m in PLACEHOLDER_LEFT.finditer(text)}), DRAFT_HANDOFF)

    identity = {name for rx, name in _COMPILED_IDENTITY if rx.search(text)}
    third, intro = _owner_name_rules()
    if third and third.search(text) and not (intro and intro.search(text)):
        identity.add("имя специалиста в третьем лице")
    if identity:
        return Verdict(HOLD, "раскрытие помощника", sorted(identity), DRAFT_HANDOFF)

    payment = [] if allow_payment else _payment_hits(text)
    if payment:
        return Verdict(HOLD, "расчёт", payment, DRAFT_HANDOFF)

    if PARTNER_PAY and PARTNER_PAY.search(text):
        return Verdict(HOLD, "оплата от партнёров", ["рассуждение о вознаграждении"], DRAFT_PARTNER_PAY)

    if UNSURE.search(text):
        return Verdict(HOLD, "неуверенность", ["модель не уверена в ответе"], DRAFT_HANDOFF)

    price = [] if allow_price else _price_hits(text)
    if price:
        return Verdict(HOLD, "цена услуг", price, DRAFT_PRICE)

    return Verdict(SEND)


