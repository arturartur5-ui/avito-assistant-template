class Outgoing(unittest.TestCase):
    def test_holds(self):
        for text, category in HOLD:
            with self.subTest(text=text):
                v = check_outgoing(text)
                self.assertFalse(v.ok, f"пропущено: {text!r}")
                self.assertEqual(v.category, category, f"{text!r}: {v.category} {v.reasons}")

    def test_sends(self):
        for text in SEND:
            with self.subTest(text=text):
                v = check_outgoing(text)
                self.assertTrue(v.ok, f"задержано зря: {text!r} — {v.category} {v.reasons}")

    def test_price_allowed_when_picture_is_complete(self):
        self.assertTrue(check_outgoing("Стоимость моих услуг 50 000 рублей", allow_price=True).ok)

    def test_empty_reply_is_held(self):
        self.assertFalse(check_outgoing("   ").ok)

    def test_long_reply_is_fast(self):
        text = "Спасибо за подробности, давайте разберём по порядку. " * 200
        started = time.perf_counter()
        check_outgoing(text)
        self.assertLess(time.perf_counter() - started, 1.0, "фильтр подвисает на длинном тексте")


