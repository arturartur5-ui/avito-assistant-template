class Consistency(unittest.TestCase):
    def test_teaching_categories_exist_in_guard(self):
        """chunking не учит модель на репликах из этих категорий — категории
        должны существовать в guard, иначе правило молча перестаёт работать."""
        import chunking
        guard_src = (Path(__file__).resolve().parent.parent / "src" / "guard.py").read_text(encoding="utf-8")
        for category in chunking.TEACHES_VIOLATION:
            with self.subTest(category=category):
                self.assertTrue(re.search(re.escape(f'"{category}"'), guard_src),
                                f"категории {category!r} в guard.py нет")


